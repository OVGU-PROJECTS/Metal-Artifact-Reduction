#!/usr/bin/env python3
"""Generate the final CNN-MAR reconstruction for a selected case.

Required per-case inputs:
  * pred_cnnmar_img.mha  - direct CNN output in HU
  * input_proj.mha       - measured projection
  * input_mask.mha       - image-domain metal mask

If ``input_metal_trace_proj.mha`` exists it is used directly; otherwise the
trace is generated by forward-projecting the metal mask.

"""
from __future__ import annotations

import argparse
from pathlib import Path

from tqdm import tqdm

from mar_common.cases import fov_from_folder, list_case_dirs
from mar_common.scanner_config import recon_config
from geometry.fanbeam import RECO_FOV
from mar_common.io import read_mha, write_mha
from postprocessing import postprocess_cnnmar


def _write_mha_atomic(image, path: Path) -> None:
    """Write through a temporary sibling so interrupted files are not accepted."""
    temporary = path.with_name(f".{path.stem}.tmp{path.suffix}")
    write_mha(image, str(temporary))
    temporary.replace(path)


def _scanner_fov_mm(case: Path) -> float:
    """Translate the shared case classifier to recon_config's FOV diameter."""
    value = fov_from_folder(str(case))
    if value in ("head", 0, "0"):
        return float(RECO_FOV["head"])
    if value in ("body", 1, "1"):
        return float(RECO_FOV["body"])
    raise ValueError(f"unsupported FOV value {value!r} for case {case.name}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build the prior and final post-processed CNN-MAR image."
    )
    parser.add_argument(
        "--data_dir", required=True, type=Path,
        help="Directory containing CNN-MAR case subdirectories.",
    )
    parser.add_argument(
        "--cnn-name", default="pred_cnnmar_img.mha",
        help="Filename of the direct CNN prediction in every case.",
    )
    parser.add_argument(
        "--prior-name", default="pred_cnnmar_prior.mha",
        help="Output filename for the segmented prior image.",
    )
    parser.add_argument(
        "--final-name", default="pred_cnnmar_final.mha",
        help="Output filename for the final post-processed reconstruction.",
    )
    parser.add_argument(
        "--projection-name", default="",
        help=(
            "Optional output filename for the corrected projection. It is not "
            "saved by default because the metric evaluation only needs the "
            "final reconstruction."
        ),
    )
    parser.add_argument(
        "--case",
        action="append",
        default=[],
        help=(
            "Process only this case ID; repeat the option for multiple cases. "
            "By default all cases are processed."
        ),
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Recompute cases that already contain the final output.",
    )
    parser.add_argument(
        "--allow-incomplete",
        action="store_true",
        help="Return success even if cases are missing inputs or fail.",
    )
    args = parser.parse_args()

    if not args.data_dir.is_dir():
        raise FileNotFoundError(f"data_dir not found: {args.data_dir}")

    cases = list_case_dirs(args.data_dir)
    requested = set(args.case)
    if requested:
        cases = [case for case in cases if case.name in requested]
        found = {case.name for case in cases}
        missing_ids = sorted(requested - found)
        if missing_ids:
            raise FileNotFoundError(
                f"requested case(s) not found: {', '.join(missing_ids)}"
            )
    if not cases:
        raise RuntimeError(f"no case directories found in {args.data_dir}")

    n_written = n_existing = n_missing = n_failed = 0
    failures: list[str] = []
    for case in tqdm(cases):
        cnn_path = case / args.cnn_name
        projection_path = case / "input_proj.mha"
        mask_path = case / "input_mask.mha"
        final_path = case / args.final_name
        if final_path.is_file() and not args.overwrite:
            print(f"[existing] {case.name}: {args.final_name}")
            n_existing += 1
            continue

        required = (cnn_path, projection_path, mask_path)
        missing = [path.name for path in required if not path.is_file()]
        if missing:
            message = f"{case.name}: missing {', '.join(missing)}"
            print(f"[missing] {message}")
            failures.append(message)
            n_missing += 1
            continue

        try:
            trace_path = case / "input_metal_trace_proj.mha"
            trace = read_mha(trace_path) if trace_path.is_file() else None
            cfg = recon_config(_scanner_fov_mm(case))
            result = postprocess_cnnmar(
                read_mha(projection_path),
                read_mha(cnn_path),
                read_mha(mask_path),
                cfg,
                metal_trace=trace,
            )

            _write_mha_atomic(result.prior_hu, case / args.prior_name)
            _write_mha_atomic(result.image_hu, final_path)
            if args.projection_name:
                _write_mha_atomic(
                    result.corrected_projection,
                    case / args.projection_name,
                )
            centers = ", ".join(
                f"{value:.1f}" for value in result.prior_info.cluster_centers_hu
            )
            print(
                f"[ok] {case.name}: centers=[{centers}] "
                f"air={result.prior_info.air_threshold_hu:.1f} "
                f"bone={result.prior_info.bone_threshold_hu:.1f}"
            )
            n_written += 1
        except Exception as error:
            message = f"{case.name}: {type(error).__name__}: {error}"
            print(f"[failed] {message}")
            failures.append(message)
            n_failed += 1

    print(
        f"[done] cases={len(cases)}, written={n_written}, "
        f"existing={n_existing}, missing={n_missing}, failed={n_failed}"
    )
    if failures:
        print("[incomplete]")
        for failure in failures:
            print(f"  {failure}")
        if not args.allow_incomplete:
            raise RuntimeError(
                f"{len(failures)} case(s) were not generated; see messages above"
            )


if __name__ == "__main__":
    main()
